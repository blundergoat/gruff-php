<?php

declare(strict_types=1);

namespace GruffPhp\Command;

use GruffPhp\Config\AnalysisConfig;
use GruffPhp\Config\ConfigLoader;
use GruffPhp\Config\SeverityThreshold;
use GruffPhp\Rule\RuleDefinition;
use GruffPhp\Rule\RuleRegistry;
use Symfony\Component\Console\Command\Command;
use Symfony\Component\Console\Input\InputInterface;
use Symfony\Component\Console\Input\InputOption;
use Symfony\Component\Console\Output\OutputInterface;
use Symfony\Component\Yaml\Exception\ParseException;
use Symfony\Component\Yaml\Yaml;

/**
 * Writes a default gruff-php YAML config file derived from the rule registry.
 */
final class InitCommand extends Command
{
    /**
     * Header inserted at the top of generated config files.
     */
    private const FILE_HEADER = "# .gruff-php.yaml\n"
        . "# Generated by `gruff-php init`. Mirrors gruff-php registry defaults; edit to customise.\n"
        . "# Add project-specific generated paths under paths.ignore, such as var/cache/** or generated/**.\n"
        . "# After reviewing current findings, `gruff-php analyse --generate-baseline` records them as known debt.\n"
        . "# Future analyse/report runs auto-apply gruff-baseline.json; use `gruff-php analyse --no-baseline` to audit without it.\n";

    /**
     * Inline depth used when dumping the YAML document.
     *
     * Keeps every list value (e.g. allowedLiterals) on its own line.
     */
    private const YAML_INLINE_DEPTH = 10;

    /**
     * Indent width matching the existing project config files.
     */
    private const YAML_INDENT = 4;

    /**
     * Default paths omitted from generated project scans.
     *
     * Keeps agent harness files, generated reports, copied vendor code, and
     * analyzer fixtures out of normal user-facing reports.
     *
     * @var list<string>
     */
    private const DEFAULT_IGNORED_PATHS = [
        '.agents/**',
        '.antigravitycli/**',
        '.claude/**',
        '.codex/**',
        '.github/**',
        '.goat-flow/**',
        'history.json',
        'infection-report.json',
        'src/Vendor/**',
        'tests/Fixtures/**',
    ];

    /**
     * Register init CLI options and metadata.
     *
     * @return void
     */
    protected function configure(): void
    {
        $this
            ->setName('init')
            ->setDescription('Write a default .gruff-php.yaml config file populated with registry defaults.')
            ->addOption('force', null, InputOption::VALUE_NONE, 'Overwrite an existing .gruff-php.yaml file.');
    }

    /**
     * Generate the default config file at the project root.
     *
     * @return int Symfony command exit code.
     */
    protected function execute(InputInterface $input, OutputInterface $output): int
    {
        $projectRoot = getcwd();
        if ($projectRoot === false) {
            $output->writeln('<error>Unable to determine current working directory.</error>');

            return Command::FAILURE;
        }

        $targetPath = $projectRoot . '/' . ConfigLoader::DEFAULT_CONFIG_FILE;
        $force      = (bool) $input->getOption('force');

        if (is_file($targetPath) && !$force) {
            $output->writeln(sprintf(
                '<error>%s already exists. Pass --force to overwrite.</error>',
                ConfigLoader::DEFAULT_CONFIG_FILE,
            ));

            return Command::FAILURE;
        }

        $registry = RuleRegistry::defaults();
        $config   = AnalysisConfig::fromRegistry($registry);

        $ignoredPaths = self::existingIgnoredPaths($targetPath) ?? self::DEFAULT_IGNORED_PATHS;
        $document     = self::buildConfigDocument($registry, $config, $ignoredPaths);
        $yaml         = Yaml::dump($document, self::YAML_INLINE_DEPTH, self::YAML_INDENT, Yaml::DUMP_EMPTY_ARRAY_AS_SEQUENCE);
        $contents     = self::FILE_HEADER . $yaml;

        if (file_put_contents($targetPath, $contents) === false) {
            $output->writeln(sprintf('<error>Unable to write %s.</error>', $targetPath));

            return Command::FAILURE;
        }

        $output->writeln(sprintf('Wrote %s', $targetPath));
        $output->writeln('');
        $output->writeln('Next steps:');
        $output->writeln('  1. Edit paths.ignore for project-local generated files.');
        $output->writeln('  2. Run `gruff-php summary` to review the current finding mix.');
        $output->writeln('  3. Optional after review: `gruff-php analyse --generate-baseline` records current findings as known debt.');
        $output->writeln('     Use `gruff-php analyse --no-baseline` to audit without that baseline.');

        return Command::SUCCESS;
    }

    /**
     * Build the YAML document mirroring registry defaults.
     *
     * @param RuleRegistry   $registry     Rule registry supplying definitions.
     * @param AnalysisConfig $config       Config seeded from the registry defaults.
     * @param list<string>   $ignoredPaths Paths to omit from generated project scans.
     * @return array<string, mixed>
     */
    private static function buildConfigDocument(RuleRegistry $registry, AnalysisConfig $config, array $ignoredPaths): array
    {
        $rules = [];
        foreach ($registry->all() as $rule) {
            $definition             = $rule->definition();
            $rules[$definition->id] = self::buildRuleEntry($definition);
        }

        return [
            'minimumPhpVersion' => $config->minimumPhpVersion(),
            'paths' => [
                'ignore' => $ignoredPaths,
            ],
            'allowlists' => [
                'acceptedAbbreviations' => [],
                'secretPreviews' => [],
            ],
            'selection' => [
                'tiers' => [],
                'pillars' => [],
                'rules' => [],
                'excludePillars' => [],
                'excludeRules' => [],
            ],
            'rules' => $rules,
        ];
    }

    /**
     * Read an existing config's path ignores so --force does not wipe local policy.
     *
     * @return list<string>|null Existing ignore paths, or null when none can be preserved.
     */
    private static function existingIgnoredPaths(string $targetPath): ?array
    {
        if (!is_file($targetPath)) {
            return null;
        }

        try {
            $decoded = Yaml::parseFile($targetPath);
        } catch (ParseException) {
            return null;
        }

        if (!is_array($decoded)) {
            return null;
        }

        $paths = $decoded['paths'] ?? null;
        if (!is_array($paths)) {
            return null;
        }

        $ignore = $paths['ignore'] ?? null;
        if (!is_array($ignore) || !array_is_list($ignore)) {
            return null;
        }

        $ignoredPaths = [];
        foreach ($ignore as $path) {
            if (!is_string($path) || trim($path) === '') {
                return null;
            }

            $ignoredPaths[] = trim($path);
        }

        return $ignoredPaths;
    }

    /**
     * Serialise one rule's registry defaults into the config shape.
     *
     * @param RuleDefinition $definition Rule definition to serialise.
     * @return array<string, mixed>
     */
    private static function buildRuleEntry(RuleDefinition $definition): array
    {
        $ruleEntry = ['enabled' => $definition->isEnabledByDefault];

        if ($definition->severityThreshold instanceof SeverityThreshold) {
            $ruleEntry['threshold'] = $definition->severityThreshold->threshold;
            $ruleEntry['severity']  = $definition->severityThreshold->severity->value;
        }

        if ($definition->defaultThresholds !== []) {
            $ruleEntry['thresholds'] = $definition->defaultThresholds;
        }

        if ($definition->defaultOptions !== []) {
            $ruleEntry['options'] = $definition->defaultOptions;
        }

        return $ruleEntry;
    }
}
